import {chromium} from 'playwright';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4317');
await page.screenshot({path:'data/desktop.png',fullPage:true});
await page.getByRole('button',{name:'Reaction replay ↗',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#buffer').textContent!=='0s',null,{timeout:30000});
await page.locator('#post').fill('2');
await page.locator('#hook').fill('CLIPCROW / FIRST FLIGHT');
await page.getByRole('button',{name:'Clip this moment'}).click();
await page.waitForSelector('a[download]',{timeout:60000});
await page.screenshot({path:'data/desktop-live.png',fullPage:true});
await page.getByRole('button',{name:'Stop capture'}).click();
await page.setViewportSize({width:375,height:900});
await page.screenshot({path:'data/mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
console.log(JSON.stringify({errors,overflow,state:await(await page.request.get('http://127.0.0.1:4317/api/state')).json()},null,2));
await browser.close();
if(errors.length||overflow)process.exitCode=1;
